package org.jazzerlang;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import javax.lang.model.SourceVersion;

/** A bounded lexer, recursive-descent parser, and deterministic Java emitter. */
public final class Compiler {
    public static final int MAX_SPEC_CHARS = 65_536;
    private Compiler() {}

    public static final class Diagnostic extends IllegalArgumentException {
        Diagnostic(int line, int column, String message) {
            super(line + ":" + column + ": " + message);
        }
    }

    private record Token(String text, int line, int column) {}
    private record Input(String type, int max) {}
    private record Spec(String name, String target, List<Input> inputs) {}
    public record Generated(String className, String source) {}

    // Restrict names to ASCII; reject Java keywords and restricted type identifiers.
    private static boolean identifier(String value) {
        return value.matches("[A-Za-z_][A-Za-z_0-9]*")
                && !SourceVersion.isKeyword(value, SourceVersion.RELEASE_21)
                && !Set.of("var", "yield", "record", "sealed", "permits").contains(value);
    }

    public static void validatePackage(String value) {
        if (value == null || value.length() > 255) throw new IllegalArgumentException("invalid package");
        for (String part : value.split("\\.", -1)) {
            if (!identifier(part)) throw new IllegalArgumentException("invalid package: " + value);
        }
    }

    public static Generated compile(String source, String packageName) {
        validatePackage(packageName);
        Spec spec = new Parser(source).parse();
        // Keep harnesses outside every possible target package (nested class names
        // are ambiguous without a classpath), so javac cannot grant package access.
        if (spec.target().startsWith(packageName + ".")) {
            throw new IllegalArgumentException("output package must not be a prefix of the target name; use an independent harness package");
        }
        String className = spec.name() + "FuzzTest";
        StringBuilder java = new StringBuilder("// Generated by JazzerLang 0.1. Do not edit.\npackage ")
                .append(packageName).append(";\n\npublic final class ").append(className).append(" {\n")
                .append("    @com.code_intelligence.jazzer.junit.FuzzTest(maxDuration = \"5s\")\n")
                .append("    public void fuzz(com.code_intelligence.jazzer.api.FuzzedDataProvider provider) throws Throwable {\n");
        for (int i = 0; i < spec.inputs().size(); i++) {
            Input input = spec.inputs().get(i);
            String type = switch (input.type()) {
                case "bytes" -> "byte[]";
                case "string" -> "java.lang.String";
                default -> input.type();
            };
            String consume = switch (input.type()) {
                case "bytes" -> "consumeBytes(" + input.max() + ")";
                case "string" -> "consumeString(" + input.max() + ")";
                case "int" -> "consumeInt()";
                case "long" -> "consumeLong()";
                case "boolean" -> "consumeBoolean()";
                default -> throw new AssertionError();
            };
            java.append("        ").append(type).append(" arg").append(i).append(" = provider.")
                    .append(consume).append(";\n");
        }
        java.append("        ").append(spec.target()).append("(");
        for (int i = 0; i < spec.inputs().size(); i++) {
            if (i > 0) java.append(", ");
            java.append("arg").append(i);
        }
        java.append(");\n    }\n}\n");
        return new Generated(className, java.toString());
    }

    private static final class Parser {
        private final String source;
        private int offset, line = 1, column = 1;
        private Token token;

        Parser(String source) {
            if (source.length() > MAX_SPEC_CHARS) throw new Diagnostic(1, 1, "spec exceeds 65536 characters");
            this.source = source;
            next();
        }

        private Diagnostic error(String message) { return new Diagnostic(token.line(), token.column(), message); }
        private void advance() {
            if (source.charAt(offset++) == '\n') { line++; column = 1; } else column++;
        }
        private void next() {
            while (offset < source.length() && " \t\r\n".indexOf(source.charAt(offset)) >= 0) advance();
            int start = offset, startLine = line, startColumn = column;
            if (offset < source.length()) {
                char c = source.charAt(offset);
                if (asciiLetter(c) || c == '_') {
                    do { advance(); } while (offset < source.length() &&
                            (asciiLetter(source.charAt(offset)) || digit(source.charAt(offset)) || source.charAt(offset) == '_'));
                } else if (digit(c)) {
                    do { advance(); } while (offset < source.length() && digit(source.charAt(offset)));
                } else if ("{};:.()=".indexOf(c) >= 0) advance();
                else throw new Diagnostic(line, column, "unexpected character");
            }
            token = new Token(source.substring(start, offset), startLine, startColumn);
        }
        private static boolean asciiLetter(char c) { return c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z'; }
        private static boolean digit(char c) { return c >= '0' && c <= '9'; }
        private void expect(String text) {
            if (!token.text().equals(text)) throw error("expected '" + text + "'");
            next();
        }
        private String name() {
            String value = token.text();
            if (!identifier(value) || value.length() > 100) throw error("expected identifier (1..100 ASCII characters, no Java keywords)");
            next();
            return value;
        }
        Spec parse() {
            expect("fuzz"); String name = name(); expect("{"); expect("target");
            List<String> parts = new ArrayList<>();
            parts.add(name());
            while (token.text().equals(".")) { next(); parts.add(name()); }
            if (parts.size() < 3) throw error("target must include package, class, and method");
            expect(";");
            List<Input> inputs = new ArrayList<>(); Set<String> names = new HashSet<>();
            while (token.text().equals("input")) {
                next();
                if (inputs.size() == 64) throw error("at most 64 inputs supported");
                if (!names.add(name())) throw error("duplicate input");
                expect(":"); String type = token.text();
                if (!Set.of("bytes", "string", "int", "long", "boolean").contains(type)) throw error("unsupported input type");
                next(); int max = 0;
                if (type.equals("bytes") || type.equals("string")) {
                    expect("("); expect("max"); expect("=");
                    try { max = Integer.parseInt(token.text()); }
                    catch (NumberFormatException e) { throw error("max must be an integer in 1..1048576"); }
                    if (max < 1 || max > 1_048_576) throw error("max must be in 1..1048576");
                    next(); expect(")");
                }
                expect(";"); inputs.add(new Input(type, max));
            }
            if (inputs.isEmpty()) throw error("at least one input required");
            expect("property"); expect("no_throw"); expect(";"); expect("}"); expect("");
            return new Spec(name, String.join(".", parts), List.copyOf(inputs));
        }
    }
}
